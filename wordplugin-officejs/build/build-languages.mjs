/** Builds browser runtimes and manifests from the editable PHP translation arrays. */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const core = fs.readFileSync(path.join(root, 'wordplugin-officejs/src/language-core.js'), 'utf8');
const php = process.env.PHP_BINARY || (process.platform === 'win32' ? 'C:/php/php.exe' : 'php');
for (const component of ['wordplugin-officejs', 'outlook-addin']) {
  const catalogs = Object.fromEntries(['de_de', 'en_us'].map(language => [language,
    JSON.parse(execFileSync(php, ['-n', '-r', '$catalog = require $argv[1]; echo json_encode($catalog, JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);',
      path.join(root, component, 'languages', language + '.php')], { encoding: 'utf8' }))]));
  const keys = Object.keys(catalogs.de_de).sort();
  if (JSON.stringify(keys) !== JSON.stringify(Object.keys(catalogs.en_us).sort())) throw new Error('Catalog keys differ: ' + component);
  for (const key of keys) {
    const tokens = value => [...value.matchAll(/\{\d+\}/g)].map(match => match[0]).sort().join();
    if (!catalogs.en_us[key] || tokens(catalogs.de_de[key]) !== tokens(catalogs.en_us[key])) throw new Error('Invalid translation: ' + component + '/' + key);
  }
  const source = '// Generated by wordplugin-officejs/build/build-languages.mjs. Edit languages/*.php instead.\n'
    + '(function(root) {\n' + core + '\nconst api = createOfficeLanguage(' + JSON.stringify(catalogs) + ');\n'
    + 'root.BerliI18n = api;\nif (typeof module !== "undefined" && module.exports) module.exports = api;\n})(globalThis);\n';
  const initializedSource = source.replace('root.BerliI18n = api;', 'root.BerliI18n = api;\nif (root.document) { api.initialize(); root.document.addEventListener?.("DOMContentLoaded", () => api.apply(root.document, true)); }');
  fs.writeFileSync(path.join(root, component, 'language.js'), initializedSource);
  const escape = value => value.replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[character]));
  const template = fs.readFileSync(path.join(root, component, 'manifest.template.xml'), 'utf8');
  const manifest = template.replace(/<(bt:String|Description|DisplayName)([^>]*?)DefaultValue="\{\{([^}]+)\}\}"([^>]*?)\s*\/>/g,
    (match, tag, before, key, after) => {
      if (!catalogs.en_us[key] || !catalogs.de_de[key]) throw new Error('Unknown manifest key: ' + key);
      const override = tag.startsWith('bt:') ? 'bt:Override' : 'Override';
      return '<' + tag + before + 'DefaultValue="' + escape(catalogs.de_de[key]) + '"' + after + '>'
        + '<' + override + ' Locale="en-US" Value="' + escape(catalogs.en_us[key]) + '"/></' + tag + '>';
    });
  if (manifest.includes('{{')) throw new Error('Unexpanded manifest translation');
  fs.writeFileSync(path.join(root, component, 'manifest.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated from manifest.template.xml and languages/*.php. -->\n' + manifest.replace(/^<\?xml[^>]+>\s*/, ''));
}
